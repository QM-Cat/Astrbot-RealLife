# ---------------------------------------------------------------------------
# 模板渲染
# ---------------------------------------------------------------------------

_PLACEHOLDER_CACHE: dict[tuple[str, ...], re.Pattern[str]] = {}


def render_template(template: str, **values: Any) -> str:
    """用 ``{name}`` 占位符渲染模板。

    只替换调用方明确传入的变量，其他花括号（例如 JSON 示例）原样保留。
    使用单次正则替换，避免变量内容里再次出现占位符时被二次展开。
    """
    if not values:
        return template

    keys = tuple(values.keys())
    pattern = _PLACEHOLDER_CACHE.get(keys)
    if pattern is None:
        joined = "|".join(re.escape(key) for key in keys)
        pattern = re.compile(r"\{(" + joined + r")\}")
        _PLACEHOLDER_CACHE[keys] = pattern

    return pattern.sub(lambda match: str(values[match.group(1)]), template)


def pick_prompt(value: Any, default: str) -> str:
    """读取配置里的提示词；空白时回退到内置默认值。"""
    if isinstance(value, str) and value.strip():
        return value.strip()
    return default
